/** Switches every dictionary in place. Callers re-render the app afterwards (see LanguageProvider). */
export function setLanguage(lang: Lang) {
  current = lang;
  Object.assign(T, DICTIONARIES[lang]);
  const m = MAPS[lang];
  Object.assign(STATUS, m.STATUS);
  Object.assign(EVIDENCE_TYPE, m.EVIDENCE_TYPE);
  Object.assign(VERIFICATION, m.VERIFICATION);
  Object.assign(ENTITY_TYPE, m.ENTITY_TYPE);
  Object.assign(RELATIONSHIP, m.RELATIONSHIP);
  Object.assign(LEVEL, m.LEVEL);
  Object.assign(LINK_PROBLEM, m.LINK_PROBLEM);
  Object.assign(RULE, m.RULE);
  if (typeof document !== 'undefined') document.documentElement.lang = lang;
}
